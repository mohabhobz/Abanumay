/**
 * القراءة · الوحدة الوحيدة اللي المساعد بيتكلم بيها في السيستم كله.
 *
 * الفكرة اللي اتجرّبت في صفحة المشروع واشتغلت: المساعد ما بيقولش
 * «فيه 4,929 مشروعًا»، بيقول «5 مشاريع عدّت حدّ قسمها، أطولها واقف
 * من 110 يومًا» · يعني جملة فيها رقم، ومصدر الرقم، وطريق يوصّلك له.
 *
 * عشان الفكرة دي تشتغل في كل شاشة، لازم تلات شروط:
 *
 *  1) القراءة **تتحسب** من نفس الداتا اللي الشاشة بتعرضها، ما تتكتبش
 *     بالإيد · وإلا هتتعارض مع الأرقام اللي قدام المستخدم أول ما
 *     الداتا تتغيّر.
 *  2) القراءة تتغيّر مع الفلتر. لو المستخدم فلتر على «بلا مالك»،
 *     المساعد يتكلم عن الشريحة دي مش عن الكل.
 *  3) القراءة يكون لها **طريق** (`to`) · تدوس عليها توديك للصفوف
 *     اللي بتتكلم عنها. وده اللي بيخلّيها أداة مش لافتة.
 */

/** إجراء صغير جنب القراءة */
export interface ReadingAction {
  label: string
  kind?: 'btn-2'
  onClick?: () => void
}

export interface Reading {
  id: string
  /** flag = مشكلة تستدعي قرار · note = ملاحظة تفيد القراءة */
  kind: 'flag' | 'note'
  /** عنوان قصير · بيظهر كوسم فوق القراءة في العرض الكامل */
  label?: string
  /**
   * الرقم الرئيسي · بيتعرض كبيرًا قبل الجملة.
   * القراءة اللي رقمها جوّه فقرة بتتقري؛ اللي رقمها كبير قدامها
   * بتتشاف. والجملة بعدها بتشرح الرقم مش بتكرّره.
   */
  metric?: { value: string; unit: string }
  text: string
  /** الكلمات اللي تتبرز · قرار تحريري، مش تخمين من النص */
  bold?: string[]
  /** اللي منها يتلوّن أحمر */
  danger?: string[]
  /** من فين الرقم · من غيره القراءة مجرد رأي */
  src?: string
  /**
   * شريط مقارنة: المستهلَك مقابل الحدّ.
   * `valueLabel`/`limitLabel` أسماء بلا أرقام · الراسم بيحطّ الرقم
   * والوحدة. لو الرقم اتكتب في الاسم كمان بيطلع مرتين.
   */
  bar?: {
    value: number
    limit: number
    valueLabel: string
    limitLabel: string
    /** وحدة تتكتب بعد الرقم: «يومًا» · «مستندًا» */
    unit?: string
  }
  actions?: ReadingAction[]
  /** الرابط اللي بيودّي للصفوف اللي القراءة بتتكلم عنها */
  to?: string
  /** نص الرابط */
  toLabel?: string
}
