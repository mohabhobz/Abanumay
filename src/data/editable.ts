/* What can be edited in each state · meeting 1 Oct, item A-6.

   The client asked that every record show "which fields are editable in it" — so a reader of the
   prototype knows, at each state, who may still change what, and what has been locked by an
   approval. This is the single source: the card on every detail page reads it, the workshop
   script cites it, and it states the rule as text so it doesn't depend on a field looking grey.

   Three lists per state:
     edit    fields the holder of the record may change now
     who     the role that holds it (and so may edit)
     locked  what is frozen at this point, and by which approval */

export type EditModule = 'registration' | 'project' | 'agreement' | 'plan' | 'payment' | 'closing'

export interface EditRule {
  who: string
  edit: string[]
  locked: string[]
  /** One line on why · shown under the lists */
  why?: string
}

